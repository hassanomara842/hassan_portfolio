let currentLang = 'en';

function setLanguage(lang) {
    currentLang = lang;
    
    // Set document direction and language attribute
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    
    // Update all translatable elements
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // Update the button text
    const langBtn = document.getElementById('lang-toggle');
    if (langBtn) {
        langBtn.textContent = lang === 'en' ? 'ع' : 'EN';
        langBtn.setAttribute('title', lang === 'en' ? 'Translate to Arabic' : 'Translate to English');
    }

    // Save preference to localStorage
    localStorage.setItem('preferredLang', lang);

    // Update Typewriter Effect Words if it exists
    updateTypewriterLang(lang);
}

// Handle Typewriter words based on language
window.typewriterWords = {
    en: ['Innovation', 'Excellence', 'Intelligence'],
    ar: ['واقع رقمي', 'تطبيقات ذكية', 'أنظمة متكاملة', 'مستقبل مبهر']
};

function updateTypewriterLang(lang) {
    // This will be picked up by the main.js typewriter logic if we modify it
    // Or we can just restart the typewriter here
    window.currentTypewriterWords = window.typewriterWords[lang];
}

document.addEventListener('DOMContentLoaded', () => {
    // Initialize typewriter words
    window.currentTypewriterWords = window.typewriterWords['en'];

    const langBtn = document.getElementById('lang-toggle');
    if (langBtn) {
        langBtn.addEventListener('click', () => {
            const newLang = currentLang === 'en' ? 'ar' : 'en';
            setLanguage(newLang);
        });
    }

    // Check for saved language preference
    const savedLang = localStorage.getItem('preferredLang');
    if (savedLang) {
        setLanguage(savedLang);
    }
});
